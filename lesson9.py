#Introduction to arithmetic operators

addition = 10+10
print('Addition', addition)

subtraction = 10-5
print('Subtraction', subtraction)

multiplication = 10*10
print('Multiplication', multiplication)

division = 10/2.2 #float
print('Division', division)

integer_division = 10//2.2 #it doesn't return the decimal value, only the integer part of the result
print('Integer Division', integer_division)

exponentiation = 2**10 #raise the number on the left to the power of the number on the right
print('Exponentiation', exponentiation)

module = 55 % 2 #return the remainder of the division, e.g. 55 / 2 = 27.5, so the remainder is 1
print('Module', module)